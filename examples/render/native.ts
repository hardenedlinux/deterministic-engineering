import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {compileFigureSource, renderCatalog} from '@deterministic-engineering/render';
const root = fileURLToPath(new URL('../../', import.meta.url));
const file = 'docs/90-99-views/90-architecture-views/90.134-render-responsibility-boundaries.d2';
const text = await readFile(path.join(root,file),'utf8');
const input = await compileFigureSource({[file]:text},file);
const result = await renderCatalog({sources:input.sources,views:[input.view],presentation:{project:input.view.title}});
if (await readFile(path.join(root,file),'utf8') !== text) throw new Error('Native view source changed');
const directory = path.join(root,'.cache/render/library-case'); await mkdir(directory,{recursive:true});
await writeFile(path.join(directory,'render-responsibility-boundaries.svg'),result.images[0]!.svg);
console.log(`native ownership view: ${result.images[0]!.nodes} nodes / ${result.images[0]!.edges} edges`);
